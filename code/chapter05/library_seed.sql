-- 이 파일은 관계를 재현하기 위해 명시적인 실습 ID를 사용합니다.
-- 명시적 ID 입력은 IDENTITY의 다음 값을 자동으로 바꾸지 않으므로 마지막에 재시작 값을 조정합니다.
-- 주의: 자동 커밋 상태에서는 일부 INSERT만 반영될 수 있으므로 실행 후 validation 파일로 확인합니다.

